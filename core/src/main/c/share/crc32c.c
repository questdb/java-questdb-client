static inline uint32_t crc32c_shift(uint32_t c) {
    return crc32c_shift_table[0][c & 0xffu]
           ^ crc32c_shift_table[1][(c >> 8) & 0xffu]
           ^ crc32c_shift_table[2][(c >> 16) & 0xffu]
           ^ crc32c_shift_table[3][c >> 24];
}

